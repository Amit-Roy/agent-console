// Browser checks use fresh data, fake accounts, and CLI guards. No live sessions or prompts.
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn, spawnSync } from "node:child_process";
import { once } from "node:events";
import { chromium } from "playwright";

const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "ac-accounts-ui-"));
const home = path.join(scratch, "home"), data = path.join(scratch, "data"), bin = path.join(scratch, "bin");
for (const dir of [home, data, bin, path.join(home, "repos"), path.join(home, ".claude")]) fs.mkdirSync(dir, {recursive:true});
fs.writeFileSync(path.join(home, ".claude", ".credentials.json"), JSON.stringify({claudeAiOauth:{accessToken:"offline-fixture"}}));
for (const name of ["claude", "codex", "pi"]) fs.writeFileSync(path.join(bin,name), "#!/bin/sh\nexit 1\n", {mode:0o700});
const now = Date.now();
const thread = (id:string, title:string, claudeAccount?:string) => ({id,title,provider:"claude",model:"sonnet",mode:"acceptEdits",cwd:path.join(home,"repos"),status:"idle",cost:0,createdAt:now,updatedAt:now,...(claudeAccount ? {claudeAccount} : {})});
fs.writeFileSync(path.join(data,"threads.json"),JSON.stringify([thread("legacy-sunny","Legacy Sunny"),thread("fixture-nefro","Nefro account","nefro")]));
fs.writeFileSync(path.join(data,"queues.json"),"{}");
fs.writeFileSync(path.join(data,"tasks.json"),"[]");
process.env.AGENT_CONSOLE_DATA = data;
const { makeToken } = await import("../server/auth.ts");
const port = process.env.ACCOUNT_TEST_PORT || "17842", base = `http://127.0.0.1:${port}`;
const server = spawn(process.execPath,["server/index.ts"],{env:{...process.env,HOME:home,CLAUDE_CONFIG_DIR:path.join(home,".claude"),PATH:bin+path.delimiter+process.env.PATH,PORT:port,AGENT_CONSOLE_DATA:data,AGENT_CONSOLE_RUN:path.join(scratch,"run"),AGENT_CONSOLE_MOCK:"1",AGENT_CONSOLE_WARM_MAX:"0"},stdio:["ignore","ignore","pipe"]});
let errors = "";
server.stderr?.on("data", chunk => errors += chunk.toString());
let browser;
const out = process.env.OUT || path.join(scratch,"screenshots");
fs.mkdirSync(out,{recursive:true});
try {
  const ready = spawnSync("waitfor",["-t","20","url",base],{encoding:"utf8"});
  assert.equal(ready.status,0, "Scratch server starts: " + errors + ready.stderr);
  browser = await chromium.launch();
  for (const [name,viewport] of [["desktop",{width:1440,height:1000}],["phone",{width:390,height:844}]] as const) {
    const context = await browser.newContext({viewport,isMobile:name === "phone",hasTouch:name === "phone"});
    await context.addCookies([{name:"ac_session",value:makeToken(),url:base}]);
    const page = await context.newPage();
    const pageErrors: string[] = [];
    page.on("pageerror", error => pageErrors.push(error.message));
    await page.goto(base);
    await page.waitForFunction(() => document.getElementById("ttl")?.textContent === "Legacy Sunny");
    assert.match(await page.locator("#thread-account").innerText(),/Sunny/);
    assert.equal(await page.locator("#usage .usage-tab").evaluateAll(buttons => buttons.every(button => button.scrollWidth <= button.clientWidth)),true,"Account usage tabs fit without overlapping labels.");
    await page.locator("#new").evaluate((el:HTMLElement) => el.click());
    await page.locator("#dlg").waitFor({state:"visible"});
    await page.locator("#d-prov").click();
    await page.getByRole("option",{name:/Claude Code/}).click();
    assert.equal(await page.locator("#account-field").isVisible(),true);
    assert.match(await page.locator("#d-account").innerText(),/Sunny/);
    await page.locator("#d-account").click();
    await page.getByRole("option",{name:/Nefro/}).click();
    assert.equal(await page.locator("#d-ok").isDisabled(),true);
    assert.equal(await page.locator("#d-account-note").isVisible(),true,"Sign-in guidance stays visible on phones.");
    assert.match(await page.locator("#d-account-note").innerText(),/Sign in/);
    await page.screenshot({path:path.join(out,`${name}-account-signin.png`),fullPage:true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,"No horizontal page overflow.");
    await page.locator("#d-prov").click();
    await page.getByRole("option",{name:/Mock/}).click();
    assert.equal(await page.locator("#account-field").isVisible(),false,"Other providers have no Claude account picker.");
    assert.equal(await page.locator("#d-ok").isDisabled(),false,"An unready Claude account cannot block another provider.");
    await page.getByRole("button",{name:"Cancel",exact:true}).click();
    await page.locator("#new").evaluate((el:HTMLElement) => el.click());
    await page.locator("#d-prov").click();
    await page.getByRole("option",{name:/Claude Code/}).click();
    assert.match(await page.locator("#d-account").innerText(),/Sunny/,"Each new thread defaults to Sunny.");
    assert.deepEqual(pageErrors,[]);
    await context.close();
  }
  const nefro = path.join(home,".claude-nefro");
  fs.mkdirSync(nefro);
  fs.writeFileSync(path.join(nefro,".credentials.json"),JSON.stringify({claudeAiOauth:{accessToken:"offline-fixture"}}));
  fs.writeFileSync(path.join(nefro,".claude.json"),JSON.stringify({oauthAccount:{emailAddress:"nefro.amit.roy@gmail.com"}}));
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  await context.addCookies([{name:"ac_session",value:makeToken(),url:base}]);
  const page = await context.newPage();
  await page.goto(base);
  await page.waitForFunction(() => document.getElementById("ttl")?.textContent === "Legacy Sunny");
  await page.locator("#new").evaluate((el:HTMLElement) => el.click());
  await page.locator("#d-prov").click();
  await page.getByRole("option",{name:/Claude Code/}).click();
  await page.locator("#d-account").click();
  await page.getByRole("option",{name:/Nefro/}).click();
  assert.equal(await page.locator("#d-ok").isEnabled(),true);
  await page.locator("#d-ok").click();
  await page.waitForFunction(() => !!document.getElementById("thread-account")?.textContent?.includes("Nefro"));
  const created = JSON.parse(fs.readFileSync(path.join(data,"threads.json"),"utf8")).find((t:any) => !["legacy-sunny","fixture-nefro"].includes(t.id));
  assert.equal(created.claudeAccount,"nefro","Create persists the selected account.");
  assert.equal(created.sessionId,undefined,"Creating a thread does not start a prompt.");
  await page.screenshot({path:path.join(out,"desktop-nefro-thread.png"),fullPage:true});
  await context.close();
  const phone = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await phone.addCookies([{name:"ac_session",value:makeToken(),url:base}]);
  const phonePage = await phone.newPage();
  await phonePage.goto(base);
  await phonePage.waitForFunction(() => !!document.getElementById("thread-account")?.textContent?.includes("Nefro"));
  await phonePage.screenshot({path:path.join(out,"phone-nefro-thread.png"),fullPage:true});
  await phone.close();
  console.log(`PASS Claude account UI: phone/desktop, legacy Sunny, Nefro sign-in and creation, account reset, provider isolation. Screenshots: ${out}`);
} finally {
  await browser?.close();
  if (server.exitCode === null && server.signalCode === null) { server.kill("SIGTERM"); await once(server,"exit"); }
  fs.rmSync(scratch,{recursive:true,force:true});
}
